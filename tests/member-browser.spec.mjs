test('20-person synthetic QA and mobile has no horizontal page overflow',async({page},testInfo)=>{
 await page.setViewportSize({width:390,height:844});
 await page.goto('/member-portal.html');
 await page.locator('#tab-audit').click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#seed20').click();
 await expect(page.locator('#member-total')).toHaveText('19');
 await expect(page.locator('#application-total')).toHaveText('19');
 await expect(page.locator('#qa-status')).toContainText('1筆年齡規則拒絕');
 await page.locator('#tab-operator').click();
 await expect(page.locator('#admin-rows tr')).toHaveCount(19);
 await page.screenshot({path:testInfo.outputPath('member-mobile-operator.png'),fullPage:true});
 const width=await page.evaluate(()=>({client:document.documentElement.clientWidth,scroll:document.documentElement.scrollWidth}));
 expect(width.scroll).toBeLessThanOrEqual(width.client);
 await page.locator('#tab-audit').click();
 page.once('dialog',dialog=>dialog.accept());
 await page.locator('#reset').click();
 await expect(page.locator('#member-total')).toHaveText('0');
 await expect(page.locator('#application-total')).toHaveText('0');
});
