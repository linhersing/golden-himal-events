import {test,expect} from '@playwright/test';
test('member account → application → NPR 500 paid mock → admin review → member progress',async({page},testInfo)=>{
 const writes=[];
 page.on('request',req=>{if(!['GET','HEAD'].includes(req.method()))writes.push(req.url())});
 await page.goto('/member-portal.html');
 await expect(page.locator('.warning')).toContainText('TEST ONLY');
 await page.locator('#persona').selectOption('T001');
 await page.locator('#signup').click();
 await expect(page.locator('#active-apply')).toContainText('MEM-TEST-0001');
 await page.locator('#round').selectOption('2027-03');
 await page.locator('#apply').click();
 await expect(page.locator('#pay-app')).toHaveValue('APP-TEST-0001');
 await page.locator('#order').click();
 await expect(page.locator('#checkout-card')).toContainText('尚未付款');
 await page.locator('#pay-success').click();
 await expect(page.locator('#checkout-card')).toContainText('模擬付款成功');
 await page.locator('#tab-operator').click();
 await expect(page.locator('#admin-rows')).toContainText('APP-TEST-0001');
 await page.getByRole('button',{name:'入圍初賽'}).click();
 await expect(page.locator('#admin-rows')).toContainText('通過Demo初篩');
 await page.locator('#tab-profile').click();
 await expect(page.locator('#profile')).toContainText('singer-001@example.invalid');
 await expect(page.locator('#my-apps')).toContainText('通過Demo初篩');
 await page.screenshot({path:testInfo.outputPath('member-desktop-account-profile.png'),fullPage:true});
 await page.reload();
 await page.locator('#signin').selectOption('MEM-TEST-0001');
 await page.locator('#login').click();
 await expect(page.locator('#my-apps')).toContainText('APP-TEST-0001');
 expect(writes).toEqual([]);
});
